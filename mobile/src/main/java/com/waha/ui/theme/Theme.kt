@Composable
fun WahaTheme(
    content: @Composable () -> Unit
) {
    val darkTheme = ThemePreferenceStore.isDarkMode.value
    val colorScheme = if (darkTheme) WahaDarkColorScheme else WahaLightColorScheme

    CompositionLocalProvider(LocalLayoutDirection provides LayoutDirection.Rtl) {
        MaterialTheme(
            colorScheme = colorScheme,
            typography = WahaTypography,
            content = content
        )
    }
}